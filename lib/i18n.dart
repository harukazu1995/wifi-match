// 表示する言語の切り替え。端末の言語が日本語・韓国語・中国語ならその言語、それ以外は英語で表示する。
//
// ソースコードの日本語の文字列は、そのまま「日本語の原文」として残してあり、
// 他の言語で表示するときだけ、下の対応表（_en / _ko / _zh）と、
// 数字や名前が入る文の規則（_patterns）で置きかえる。
// 新しい言語を足すときは、対応表を1つ増やし、_table と _patterns を広げる。
import 'package:flutter/material.dart' as m;
import 'package:flutter/widgets.dart';

String get _lang {
  final c = WidgetsBinding.instance.platformDispatcher.locale.languageCode;
  return (c == 'ja' || c == 'ko' || c == 'zh') ? c : 'en';
}

bool get isJapanese => _lang == 'ja';

Map<String, String> _table(String lang) => lang == 'ko' ? _ko : (lang == 'zh' ? _zh : _en);

/// 日本語の原文を、端末の言語に合わせた文字列にする。対応がないものは、そのまま返す。
String tr(String s) {
  final lang = _lang;
  if (lang == 'ja') return s;
  final direct = _table(lang)[s];
  if (direct != null) return direct;
  for (final (re, f) in _patterns) {
    final match = re.firstMatch(s);
    if (match != null) return f(match, lang);
  }
  return s;
}

String _t(String lang, String en, String ko, String zh) => lang == 'ko' ? ko : (lang == 'zh' ? zh : en);

String _n(String lang, String s) => s == '誰か' ? _t(lang, 'Someone', '누군가', '某人') : s;

